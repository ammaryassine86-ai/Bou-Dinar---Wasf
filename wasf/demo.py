def make_demo(folder: Path, langue: str = "fr") -> dict[str, Path]:
    media.require_ffmpeg()
    spec = DEMOS.get(langue, DEMOS["fr"])
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)

    video = folder / "clip_demo.mp4"
    speech = "+".join(f"between(t,{a},{b})" for a, b, _ in spec["dialogues"])
    audio = (f"aevalsrc='0.25*sin(2*PI*220*t)*(0.6+0.4*sin(2*PI*3*t))*({speech})'"
             ":s=48000:d=30")
    graph = ("color=c=0x264653:s=1280x720:r=25:d=10[bg1];color=c=0xe9c46a:s=180x120:r=25:d=10[box1];"
             "[bg1][box1]overlay=x='100+60*t':y=300:shortest=1[s1];"
             "testsrc2=s=1280x720:r=25:d=10[s2];"
             "color=c=0x1d3557:s=1280x720:r=25:d=10[bg3];color=c=0xf4a261:s=200x200:r=25:d=10[box3];"
             "[bg3][box3]overlay=x=540:y=260:shortest=1,fade=t=out:st=7:d=3[s3];"
             "[s1][s2][s3]concat=n=3:v=1:a=0,format=yuv420p[v]")
    media.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", audio,
               "-filter_complex", graph, "-map", "[v]", "-map", "0:a", "-c:v", "libx264",
               "-preset", "veryfast", "-crf", "26", "-c:a", "aac", "-b:a", "128k", "-shortest",
               str(video)])

    srt = folder / "clip_demo.srt"
    srt.write_text("\n".join(f"{i}\n{fmt_tc(a, ',')} --> {fmt_tc(b, ',')}\n{text}\n"
                             for i, (a, b, text) in enumerate(spec["dialogues"], 1)),
                   encoding="utf-8")

    intent = {
        "film": spec["film"],
        "realisateur": "Équipe Wasf",
        "langue": "aeb" if langue == "aeb" else ("ar" if langue == "ar" else "fr"),
        "descripteur": "",
        "droits": {"accord_producteur": True,
                   "reference": "Clip de démonstration généré par Wasf : aucun droit de tiers."},
        "intention_globale": spec["intention"],
        "scenes": [{"debut": a, "fin": b, "a_remarquer": note, "a_eviter": avoid}
                   for a, b, note, avoid in spec["scenes"]],
    }
    if spec.get("exemples"):
        intent["exemples"] = spec["exemples"]
    intent_path = folder / "intention_demo.yaml"
    intent_path.write_text("# Intention de la réalisation pour le clip de démonstration\n"
                           + yaml.safe_dump(intent, allow_unicode=True, sort_keys=False),
                           encoding="utf-8")
    return {"video": video, "sous_titres": srt, "intention": intent_path}
